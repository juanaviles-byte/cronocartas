const HUELLAS_URL = './__huellas__';

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const nueva = await caches.open(VERSION);
    // La versión instalada antes (si hay) y las huellas con que se guardó.
    let previa = null, huellasPrevias = {};
    for (const k of await caches.keys()) {
      if (k === VERSION) continue;
      const c = await caches.open(k);
      const r = await c.match(HUELLAS_URL);
      if (r) { previa = c; huellasPrevias = await r.json().catch(() => ({})); break; }
    }
    // Lo que no cambió se copia de la versión anterior; el resto se descarga.
    const pendientes = [];
    for (const u of ARCHIVOS) {
      if (previa && huellasPrevias[u] === HUELLAS[u]) {
        const r = await previa.match(u);
        if (r) { await nueva.put(u, r); continue; }
      }
      pendientes.push(u);
    }
    // cache: 'reload' evita copiar archivos viejos desde la caché HTTP del navegador.
    await nueva.addAll(pendientes.map(u => new Request(u, { cache: 'reload' })));
    await nueva.put(HUELLAS_URL, new Response(JSON.stringify(HUELLAS), { headers: { 'content-type': 'application/json' } }));
  })().then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Responde desde la caché al instante y, si hay internet, la actualiza por detrás.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.open(VERSION).then(async cache => {
    const guardado = await cache.match(e.request, { ignoreSearch: true });
    const red = fetch(e.request).then(r => { if (r.ok) cache.put(e.request, r.clone()); return r; }).catch(() => null);
    e.waitUntil(red);
    // La página de inicio solo reemplaza a una página; nunca a un dato, una imagen o un audio.
    return guardado || (await red) || (e.request.mode === 'navigate' ? cache.match('index.html') : Response.error());
  }));
});
